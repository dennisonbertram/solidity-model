"""Quantize train/weights.json to int16 fixed-point and emit src/Weights.sol
(bytes constants + layout offsets consumed by src/OnChainLLM.sol)."""
import json
import math
import struct

SCALE = 4096  # Q12 fixed point: real = int16_value / SCALE

with open("train/weights.json") as f:
    d = json.load(f)

VOCAB, C, T, HID, V = d["vocab"], d["C"], d["T"], d["HID"], d["V"]
state = d["state"]


def quantize(name):
    flat = []

    def walk(x):
        if isinstance(x, list):
            for e in x:
                walk(e)
        else:
            flat.append(x)

    walk(state[name])
    q = []
    clipped = 0
    for v in flat:
        iv = round(v * SCALE)
        if iv > 32767 or iv < -32768:
            clipped += 1
        iv = max(-32768, min(32767, iv))
        q.append(iv)
    if clipped:
        print(f"WARNING: {name} clipped {clipped}/{len(flat)} values")
    return q


# Layout: order matters, must match OnChainLLM.sol reader offsets.
LAYOUT = ["tok_emb", "pos_emb", "Wq", "Wk", "Wv", "Wo", "attn_norm_gain",
          "W1", "b1", "W2", "b2", "ffn_norm_gain", "final_norm_gain"]

params = []
offsets = {}
for name in LAYOUT:
    offsets[name] = len(params)
    params.extend(quantize(name))

params_bytes = b"".join(struct.pack("<h", v) for v in params)
print(f"PARAMS: {len(params)} int16 values, {len(params_bytes)} bytes")

# Exp lookup table for fixed-point softmax. Domain covers observed attention
# score range [{:.2f}, {:.2f}] with margin.
LUT_MIN, LUT_MAX, LUT_N = -14.0, 14.0, 281
LUT_STEP = (LUT_MAX - LUT_MIN) / (LUT_N - 1)
LUT_SCALE = 10 ** 9

lut = []
for i in range(LUT_N):
    x = LUT_MIN + i * LUT_STEP
    lut.append(round(math.exp(x) * LUT_SCALE))
assert max(lut) < 2**64, "LUT overflow uint64"
lut_bytes = b"".join(struct.pack("<Q", v) for v in lut)
print(f"EXP_LUT: {LUT_N} uint64 values, {len(lut_bytes)} bytes, "
      f"max={max(lut)} (uint64 max={2**64-1})")

vocab_bytes = VOCAB.encode("ascii")

sol = f"""// SPDX-License-Identifier: MIT
pragma solidity ^0.8.24;

// Auto-generated by train/export.py. Do not edit by hand — re-run the
// training + export pipeline to regenerate.
abstract contract Weights {{
    uint256 internal constant SCALE = {SCALE};
    uint256 internal constant V = {V};
    uint256 internal constant C = {C};
    uint256 internal constant TBLOCK = {T};
    uint256 internal constant HID = {HID};

    // byte offsets into PARAMS, in units of int16 elements (multiply by 2 for byte offset)
    uint256 internal constant OFF_TOK_EMB = {offsets["tok_emb"]};
    uint256 internal constant OFF_POS_EMB = {offsets["pos_emb"]};
    uint256 internal constant OFF_WQ = {offsets["Wq"]};
    uint256 internal constant OFF_WK = {offsets["Wk"]};
    uint256 internal constant OFF_WV = {offsets["Wv"]};
    uint256 internal constant OFF_WO = {offsets["Wo"]};
    uint256 internal constant OFF_ATTN_NORM_GAIN = {offsets["attn_norm_gain"]};
    uint256 internal constant OFF_W1 = {offsets["W1"]};
    uint256 internal constant OFF_B1 = {offsets["b1"]};
    uint256 internal constant OFF_W2 = {offsets["W2"]};
    uint256 internal constant OFF_B2 = {offsets["b2"]};
    uint256 internal constant OFF_FFN_NORM_GAIN = {offsets["ffn_norm_gain"]};
    uint256 internal constant OFF_FINAL_NORM_GAIN = {offsets["final_norm_gain"]};

    int256 internal constant LUT_MIN_FIXED = {round(LUT_MIN * SCALE)};
    int256 internal constant LUT_MAX_FIXED = {round(LUT_MAX * SCALE)};
    uint256 internal constant LUT_N = {LUT_N};
    uint256 internal constant LUT_SCALE = {LUT_SCALE};

    bytes internal constant VOCAB_BYTES = hex"{vocab_bytes.hex()}";

    bytes internal constant PARAMS =
        hex"{params_bytes.hex()}";

    bytes internal constant EXP_LUT =
        hex"{lut_bytes.hex()}";
}}
"""

with open("src/Weights.sol", "w") as f:
    f.write(sol)
print("wrote src/Weights.sol")
